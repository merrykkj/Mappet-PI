-- ------------------------------------------------------------
-- ESPECIE: dominio das especies validas (UC08) e filtro (UC04)
-- ------------------------------------------------------------
CREATE TABLE T_MAPPET_ESPECIE (
    ID_ESPECIE  NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME        VARCHAR2(30)  NOT NULL,
    CONSTRAINT PK_ESPECIE      PRIMARY KEY (ID_ESPECIE),
    CONSTRAINT UK_ESPECIE_NOME UNIQUE (NOME)
);


-- ------------------------------------------------------------
-- USUARIO: conta da plataforma (UC01, UC02)
-- Tutor, Acolhedor e Adotante sao papeis, nao tabelas
-- ------------------------------------------------------------
CREATE TABLE T_MAPPET_USUARIO (
    ID_USUARIO  NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME        VARCHAR2(100)  NOT NULL,
    EMAIL       VARCHAR2(150)  NOT NULL,
    TELEFONE    VARCHAR2(15)   NOT NULL,
    SENHA_HASH  VARCHAR2(255)  NOT NULL,   -- somente o hash da senha (UC01, passo 7)
    CONSTRAINT PK_USUARIO       PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL)              -- UC01, excecao E2
);


-- ------------------------------------------------------------
-- PUBLICACAO_PET: pets perdidos e encontrados (UC05, UC06)
-- ------------------------------------------------------------
CREATE TABLE T_MAPPET_PUBLICACAO_PET (
    ID_PUBLICACAO    NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TIPO             VARCHAR2(10)   NOT NULL,
    NOME_PET         VARCHAR2(60)   NOT NULL,
    BAIRRO           VARCHAR2(80)   NOT NULL,
    FOTO_URL         VARCHAR2(255)  NOT NULL,   -- caminho da imagem JPG ou PNG (UC07)
    DATA_PUBLICACAO  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    ID_USUARIO       NUMBER(10)     NOT NULL,
    ID_ESPECIE       NUMBER(10)     NOT NULL,
    CONSTRAINT PK_PUBLICACAO         PRIMARY KEY (ID_PUBLICACAO),
    CONSTRAINT CK_PUBLICACAO_TIPO    CHECK (TIPO IN ('perdido', 'encontrado')),
    CONSTRAINT FK_PUBLICACAO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES T_MAPPET_USUARIO (ID_USUARIO),
    CONSTRAINT FK_PUBLICACAO_ESPECIE FOREIGN KEY (ID_ESPECIE)
        REFERENCES T_MAPPET_ESPECIE (ID_ESPECIE)
);


-- ------------------------------------------------------------
-- ANIMAL_ADOCAO: animais em lar temporario (UC10, consultados no UC09)
-- ------------------------------------------------------------
CREATE TABLE T_MAPPET_ANIMAL_ADOCAO (
    ID_ANIMAL      NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME           VARCHAR2(60)   NOT NULL,
    BAIRRO         VARCHAR2(80)   NOT NULL,
    DESCRICAO      CLOB           NOT NULL,
    FOTO_URL       VARCHAR2(255)  NOT NULL,
    DATA_CADASTRO  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    ID_USUARIO     NUMBER(10)     NOT NULL,
    ID_ESPECIE     NUMBER(10)     NOT NULL,
    CONSTRAINT PK_ANIMAL         PRIMARY KEY (ID_ANIMAL),
    CONSTRAINT FK_ANIMAL_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES T_MAPPET_USUARIO (ID_USUARIO),
    CONSTRAINT FK_ANIMAL_ESPECIE FOREIGN KEY (ID_ESPECIE)
        REFERENCES T_MAPPET_ESPECIE (ID_ESPECIE)
);


-- ------------------------------------------------------------
-- INTERESSE_ADOCAO: relacionamento N:N "manifesta interesse" (UC11)
-- Registra quem recebeu o contato do acolhedor, para qual animal e quando
-- ------------------------------------------------------------
CREATE TABLE T_MAPPET_INTERESSE_ADOCAO (
    ID_USUARIO      NUMBER(10)  NOT NULL,
    ID_ANIMAL       NUMBER(10)  NOT NULL,
    DATA_INTERESSE  TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INTERESSE         PRIMARY KEY (ID_USUARIO, ID_ANIMAL),
    CONSTRAINT FK_INTERESSE_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES T_MAPPET_USUARIO (ID_USUARIO),
    CONSTRAINT FK_INTERESSE_ANIMAL  FOREIGN KEY (ID_ANIMAL)
        REFERENCES T_MAPPET_ANIMAL_ADOCAO (ID_ANIMAL)
);


-- ------------------------------------------------------------
-- INDICES
-- O Oracle cria indice automatico so para PK e UNIQUE.
-- UC03: Home com as mais recentes | UC04: filtros | FK: chaves estrangeiras
-- ------------------------------------------------------------
CREATE INDEX IDX_PUBLICACAO_DATA    ON T_MAPPET_PUBLICACAO_PET (DATA_PUBLICACAO);    -- UC03
CREATE INDEX IDX_PUBLICACAO_FILTRO  ON T_MAPPET_PUBLICACAO_PET (ID_ESPECIE, BAIRRO); -- UC04
CREATE INDEX IDX_PUBLICACAO_USUARIO ON T_MAPPET_PUBLICACAO_PET (ID_USUARIO);         -- FK
CREATE INDEX IDX_ANIMAL_DATA        ON T_MAPPET_ANIMAL_ADOCAO (DATA_CADASTRO);       -- MLR
CREATE INDEX IDX_ANIMAL_ESPECIE     ON T_MAPPET_ANIMAL_ADOCAO (ID_ESPECIE);          -- FK
CREATE INDEX IDX_ANIMAL_USUARIO     ON T_MAPPET_ANIMAL_ADOCAO (ID_USUARIO);          -- FK
CREATE INDEX IDX_INTERESSE_ANIMAL   ON T_MAPPET_INTERESSE_ADOCAO (ID_ANIMAL);        -- FK


